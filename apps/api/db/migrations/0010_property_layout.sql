-- Layout of the Properties panel: the sections it shows and where each prop of each component goes. The catalog in
-- code keeps the structure of the props (schema, validation, references); these tables keep only how they are
-- presented, so sections, order and labels change without a deploy of the web app or the API.
create type studio.property_nature as enum ('content', 'logic', 'behavior', 'appearance', 'motion', 'placement', 'other')
--;
-- A section of the panel. `position` orders the sections for every component; `nature` states what kind of setting the
-- section holds. The single fallback section receives props that have no row in `component_property`.
create table studio.property_section (
  key text primary key check (key ~ '^[a-z][a-z0-9_]*$'),
  nature studio.property_nature not null,
  position smallint not null check (position >= 1),
  labels jsonb not null check (jsonb_typeof(labels) = 'object' and labels ? 'es'),
  is_fallback boolean not null default false,
  constraint property_section_position_key unique (position) deferrable initially deferred
)
--;
create unique index property_section_single_fallback_idx on studio.property_section (is_fallback) where is_fallback
--;
-- Placement of one prop of one component. `component` is a catalog key, or `*` for the fields every element has
-- (name, geometry, entrance and appearance time). `position` orders the props inside their section. `visible_when`
-- shows the prop only when another prop of the element matches: `{ prop, op }` with `op` one of `empty`, `notEmpty`,
-- `equals` (with `value`) or `in` (with `values`). `labels` and `help` override the generic texts of the web app.
create table studio.component_property (
  component text not null check (component = '*' or component ~ '^[a-z][a-z0-9_]*$'),
  prop_key text not null check (prop_key ~ '^[A-Za-z][A-Za-z0-9]*$'),
  section_key text not null references studio.property_section (key) on update cascade on delete restrict,
  position smallint not null check (position >= 0),
  advanced boolean not null default false,
  visible_when jsonb check (visible_when is null or (jsonb_typeof(visible_when) = 'object' and visible_when ? 'prop' and visible_when ? 'op')),
  labels jsonb check (labels is null or jsonb_typeof(labels) = 'object'),
  help jsonb check (help is null or jsonb_typeof(help) = 'object'),
  primary key (component, prop_key)
)
--;
create index component_property_section_key_idx on studio.component_property (section_key)
